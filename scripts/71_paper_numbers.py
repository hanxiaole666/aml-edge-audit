def signlaw(m: Macros, t: Tables) -> None:
    d = load("sign_law")
    v = d["verdict"]
    m.add("LAWrTwoH", f3(v["r2_H_all"]))
    m.add("LAWrTwoN", f3(v["r2_N_all"]))
    m.add("LAWrRealH", f3(v["r2_H_real"]))
    m.add("LAWnAll", str(d["fit_H_all"]["n"]))
    m.add("LAWcoefDeg", f3(d["fit_H_all"]["coef"]["delta_degree"]))
    m.add("LAWcoefEx", s3(d["fit_H_all"]["coef"]["excess"]))
    m.add("LAWcoefExReal", s3(d["fit_H_real"]["coef"]["excess"]))
    m.add("LAWcoefNbr", f3(d["fit_N_all"]["coef"]["delta_nbr_auc"]))
    m.add("LAWsupported", "supported" if v["law_supported_N"] else "not supported")

    # LOGO 的最差 R^2 与最好符号一致率
    logos = []
    for fam in ("logo_H", "logo_N"):
        for k, x in d[fam].items():
            if x["r2"] == x["r2"]:  # not NaN
                logos.append((fam, k, x["r2"], x["sign_agreement"]))
    worst_r2 = min(x[2] for x in logos if x[2] > -1e6)
    best_sign = max(x[3] for x in logos)
    m.add("LAWlogoWorst", f"{worst_r2:.1f}")
    m.add("LAWlogoSign", f3(best_sign))

    lines = []
    for fam, lab in (("fit_H_all", "all 29 conditions"), ("fit_H_real", "Real-CATS only (19)")):
        f = d[fam]
        lines.append(f"{lab} & {f['coef']['delta_degree']:+.3f} & {f['coef']['excess']:+.3f} & "
                     f"{f['r2']:.3f} & {f['rmse']:.3f} & {f['n']} \\\\")
    lines.append("\\midrule")
    for k, x in d["logo_H"].items():
        neg = "yes" if (x["r2"] != x["r2"] or x["r2"] < 0) else "no"
        lines.append(f"LOGO {k.replace('_', ' ')} & \\multicolumn{{2}}{{c}}{{$R^2<0$: {neg}}} & "
                     f"\\multicolumn{{3}}{{c}}{{sign agreement {100 * x['sign_agreement']:.0f}\\%}} \\\\")

    body = (
        "\\begin{tabular}{@{}lccccc@{}}\n\\toprule\n"
        "Sample & $\\beta_{\\Delta\\text{deg}}$ & $\\beta_{\\text{excess}}$ & $R^2$ & RMSE & $n$ \\\\\n"
        "\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n"
    )
    t.add("tab_signlaw.tex",
          "Regressing $\\Delta$AP on the change in test-node degree and on the homophily excess "
          "of the edges a condition adds or removes. The pooled fit is descriptive; the "
          "leave-one-graph-out rows show it does not transport across graphs.",
          "tab:signlaw", body)


