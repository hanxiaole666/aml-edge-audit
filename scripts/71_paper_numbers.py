"""
71_paper_numbers.py - 论文数字单一来源
=======================================
把 results/*.json 里已被实验确认的数字，直接编译成
  submission_tdsc/generated/numbers.tex   正文引用的宏
  submission_tdsc/generated/tab_*.tex     正文表格
并输出 results/paper_numbers.json 供 24_consistency_check.py 复核。

设计原则：论文正文不再手写任何实验数字。凡是要出现在正文里的量，
都在这里定义一个宏；凡是表格，都由本脚本从结果文件渲染。
这样"论文里的数与结果文件里的数"在构造上无法分叉。

用法：python scripts/71_paper_numbers.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
OUT = ROOT / "submission_tdsc" / "generated"


def load(name: str) -> dict:
    with open(RES / f"{name}.json", encoding="utf-8") as f:
        return json.load(f)


def f3(x) -> str:
    return f"{x:.3f}"


def s3(x) -> str:
    """带符号的三位小数，用于 Δ 列。"""
    return f"{x:+.3f}"


def f2(x) -> str:
    return f"{x:.2f}"


def pct(x) -> str:
    return f"{100 * x:.1f}"


class Macros:
    def __init__(self) -> None:
        self.items: dict[str, str] = {}

    def add(self, name: str, value: str) -> None:
        assert name not in self.items, f"duplicate macro {name}"
        # LaTeX control words are letters only: a digit terminates the control
        # sequence, so \RCCC1 would expand as \RCCC followed by "1".
        assert not any(c.isdigit() for c in name), (
            f"macro name {name} contains a digit; use a spelled-out tag")
        self.items[name] = value

    def render(self) -> str:
        head = [
            "% AUTO-GENERATED by scripts/71_paper_numbers.py -- do not edit by hand.",
            "% Every experimental number in the manuscript is defined here.",
            "",
        ]
        body = [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in self.items.items()]
        return "\n".join(head + body) + "\n"


class Tables:
    def __init__(self) -> None:
        self.items: dict[str, str] = {}

    def add(self, filename: str, caption: str, label: str, body: str, note: str = "") -> None:
        note_tex = f"\n\\par\\smallskip\\footnotesize {note}\n" if note else "\n"
        tex = (
            "% AUTO-GENERATED by scripts/71_paper_numbers.py\n"
            "\\begin{table}[!t]\n"
            f"\\caption{{{caption}}}\n"
            f"\\label{{{label}}}\n"
            "\\centering\n"
            "\\footnotesize\n"
            "\\setlength{\\tabcolsep}{2.5pt}\n"
            f"{body}"
            f"{note_tex}"
            "\\end{table}\n"
        )
        self.items[filename] = tex

    def write(self) -> None:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, tex in self.items.items():
            (OUT / name).write_text(tex, encoding="utf-8")


# ---------------------------------------------------------------- Real-CATS 四条件
def realcats_edges(m: Macros, t: Tables) -> dict:
    d = load("edge_protocol_final")
    rows = d["splits"]
    agg = d["aggregate"]
    pt = d["paired_tests"]

    for k, tag in (("C1", "cone"), ("C2", "ctwo"), ("C3", "cthree"), ("M2", "mtwo")):
        m.add(f"RCC{tag}", f3(agg[k]["AP_mean"]))
        m.add(f"RCC{tag}sd", f3(agg[k]["AP_std"]))

    m.add("RCCthreeGain", f3(agg["C3"]["AP_mean"] - agg["C1"]["AP_mean"]))
    m.add("RCCmTwoGap", f3(agg["C1"]["AP_mean"] - agg["M2"]["AP_mean"]))
    m.add("RCCtwoDrop", f3(agg["C1"]["AP_mean"] - agg["M2"]["AP_mean"]))
    m.add("RCCtwoVsThree", f3(agg["C2"]["AP_mean"] - agg["C3"]["AP_mean"]))
    m.add("RCCpairCtwoCthreeCI", f"[{pt['C2_vs_C3']['ci95'][0]:.3f}, {pt['C2_vs_C3']['ci95'][1]:.3f}]")
    m.add("RCCpairCtwoMtwo", f3(pt["C2_vs_M2"]["diff"]))
    m.add("RCCpairCtwoMtwoCI", f"[{pt['C2_vs_M2']['ci95'][0]:.3f}, {pt['C2_vs_M2']['ci95'][1]:.3f}]")
    m.add("RCCnSplits", str(d["n_splits"]))
    c1c3 = [r["C3_minus_C1"]["diff"] for r in rows]
    m.add("RCCcOneCthree", f3(float(sum(c1c3) / len(c1c3))))
    lo = min(r["C3_minus_C1"]["ci95"][0] for r in rows)
    hi = max(r["C3_minus_C1"]["ci95"][1] for r in rows)
    m.add("RCCcOneCthreeCI", f"[{lo:.3f}, {hi:.3f}]")

    # 逐切分是否 M2 最低
    m2_lowest = all(r["conditions"]["M2"]["AP"] < min(
        r["conditions"][k]["AP"] for k in ("C1", "C2", "C3")) for r in rows)
    m.add("RCCmTwoAlwaysLowest", "yes" if m2_lowest else "no")

    lines = []
    for r in rows:
        c = r["conditions"]
        lines.append(
            f"{r['frac']:.2f} & {r['n_test']:,} & {r['test_prevalence']:.3f} & "
            f"{c['C1']['AP']:.3f} & {c['C2']['AP']:.3f} & {c['C3']['AP']:.3f} & {c['M2']['AP']:.3f} \\\\"
        )
    body = (
        "\\begin{tabular}{@{}lcccccc@{}}\n\\toprule\n"
        "Cutoff & $n_{\\text{test}}$ & Prev. & C1 & C2 & C3 & M2 \\\\\n\\midrule\n"
        + "\n".join(lines)
        + "\n\\midrule\n"
        + f"mean & & & {agg['C1']['AP_mean']:.3f} & {agg['C2']['AP_mean']:.3f} & "
        f"{agg['C3']['AP_mean']:.3f} & {agg['M2']['AP_mean']:.3f} \\\\\n"
        + f"std & & & {agg['C1']['AP_std']:.3f} & {agg['C2']['AP_std']:.3f} & "
        f"{agg['C3']['AP_std']:.3f} & {agg['M2']['AP_std']:.3f} \\\\\n"
        "\\bottomrule\n\\end{tabular}\n"
    )

    # 第二 panel：0.75 折的机制诊断（同一张图，同一个 M2 随机流）
    mech = load("mechanism_diagnostics")["conditions"]
    mc = {k: mech[k] for k in ("C1", "C2", "C3", "M2")}
    for k, tag in (("C1", "cone"), ("C2", "ctwo"), ("C3", "cthree"), ("M2", "mtwo")):
        v = mc[k]
        m.add(f"MECH{tag}ap", f3(v["PR_AUC"]))
        m.add(f"MECH{tag}deg", f"{v['test_degree']['mean']:.2f}")
        m.add(f"MECH{tag}cov", pct(v["neighbor_label"]["coverage"]))
        m.add(f"MECH{tag}mmd", f"{v['MMD_to_C3']:.4f}")
        auc = v["neighbor_label"]["frac_pos_label_AUC"]
        m.add(f"MECH{tag}nbr", "---" if auc is None else f3(auc))

    def cell(k, field, fmt):
        v = mc[k][field]
        return "---" if v is None else fmt(v)

    rows = [
        ("PR-AUC & " + " & ".join(f"{mc[k]['PR_AUC']:.3f}" for k in mc)),
        ("Test-node degree (mean) & " + " & ".join(f"{mc[k]['test_degree']['mean']:.2f}" for k in mc)),
        ("Test nodes with $\geq$1 training-end neighbour & " + " & ".join(f"{100 * mc[k]['neighbor_label']['coverage']:.1f}\\%" for k in mc)),
        ("Neighbour-label AUC & " + " & ".join(
            "---" if mc[k]["neighbor_label"]["frac_pos_label_AUC"] is None
            else f"{mc[k]['neighbor_label']['frac_pos_label_AUC']:.3f}" for k in mc)),
        ("RBF-MMD to the C3 representation & " + " & ".join(f"{mc[k]['MMD_to_C3']:.4f}" for k in mc)),
    ]
    mech_tex = (
        "\\vspace{4pt}\n\\begin{tabular}{@{}lcccc@{}}\n\\toprule\n"
        "Quantity (0.75 cutoff) & C1 & C2 & C3 & M2 \\\\\n\\midrule\n"
        + "\n".join(r + " \\\\" for r in rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )

    t.add("tab_edgeprotocol.tex",
          "Four-condition edge audit on the Real-CATS co-occurrence graph over five temporal "
          "cutoffs (logistic read-out, 2-hop normalised adjacency). M2 draws uniformly random "
          "pairs at the C2 edge count, not a subset of the observed edge list. Lower panel: "
          "mechanism diagnostics at the 0.75 cutoff on the same graph.",
          "tab:edgeprotocol", body + mech_tex)

    m.add("MECHmmdRatio", f"{mc['M2']['MMD_to_C3'] / max(mc['C1']['MMD_to_C3'], 1e-9):.0f}")
    m.add("MECHdegGap", f"{abs(mc['C1']['test_degree']['mean'] - mc['M2']['test_degree']['mean']):.2f}")
    m.add("MECHcovGap", f"{100 * (mc['M2']['neighbor_label']['coverage'] - mc['C1']['neighbor_label']['coverage']):.1f}")
    return d


# ---------------------------------------------------------------- 机制诊断 0.75
def mechanism(m: Macros, t: Tables, hom: dict) -> None:
    r75 = next(r for r in hom["real_cats"] if r["split"] == "frac=0.75")
    ce = r75["cross_edges"]
    m.add("HOMobs", f3(ce["observed_same"]))
    m.add("HOMexp", f3(ce["expected_independent"]))
    m.add("HOMexcess", f3(ce["excess"]))
    ex = [r["cross_edges"]["excess"] for r in hom["real_cats"]]
    m.add("HOMexcessMean", f3(sum(ex) / len(ex)))
    m.add("HOMcrossMean", f"{sum(r['cross_edges']['n_edges'] for r in hom['real_cats']) / len(hom['real_cats']):,.0f}")

    m.add("HOMtestTest", f3(r75["test_test_edges"]["excess"]))
    m.add("HOMtrainTrain", f3(r75["train_train_edges"]["excess"]))
    m.add("HOMall", f3(r75["all_edges"]["excess"]))


# ---------------------------------------------------------------- Elliptic 四条件
def elliptic_edges(m: Macros, t: Tables) -> dict:
    d = load("elliptic_v1_strong_model")
    agg = d["aggregate_nondegenerate"]
    m.add("ELCone", f3(agg["C1"]["mean"]))
    m.add("ELCtwo", f3(agg["C2"]["mean"]))
    m.add("ELCthree", f3(agg["C3"]["mean"]))
    m.add("ELCmtwo", f3(agg["M2"]["mean"]))
    m.add("ELCmTwoAboveCthree", f3(agg["M2"]["mean"] - agg["C3"]["mean"]))
    m.add("ELConeMinusCthree", f3(agg["C1"]["mean"] - agg["C3"]["mean"]))

    hom = load("cross_edge_homophily")
    tt = [r["test_test_edges"]["excess"] for r in hom["elliptic_v1"] if r.get("test_test_edges")]
    m.add("ELCttExLo", f3(min(tt)))
    m.add("ELCttExHi", f3(max(tt)))
    m.add("ELCmaxStepGap", str(max(r.get("max_step_gap", 0) for r in hom["elliptic_v1"])));
    m.add("ELCcrossEdges", str(sum(r.get("n_cross_edges", 0) for r in hom["elliptic_v1"])))
    deg = d["degenerate_folds"][0]
    m.add("ELCdegPrev", f3(deg["test_prevalence"]))
    m.add("ELCdegCutoff", str(deg["cutoff"]))
    m.add("ELCdegCone", f3(deg["AP_by_condition"]["C1"]))
    m.add("ELCdegCtwo", f3(deg["AP_by_condition"]["C2"]))

    rows = []
    for r in d["splits"]:
        c = r["conditions"]
        if r["cutoff"] == deg["cutoff"]:
            rows.append("\\midrule")
            tag = "\\multicolumn{2}{@{}l@{}}{mean, 30--39}"
            rows.append(f"{tag} & & {agg['C1']['mean']:.3f} & {agg['C2']['mean']:.3f} & "
                        f"{agg['C3']['mean']:.3f} & {agg['M2']['mean']:.3f} \\\\")
            rows.append("\\midrule")
        rows.append(
            f"{r['cutoff']} & {r['n_test']:,} & {r['test_prevalence']:.3f} & "
            f"{c['C1']['AP']:.3f} & {c['C2']['AP']:.3f} & {c['C3']['AP']:.3f} & {c['M2']['AP']:.3f} \\\\"
        )
    body = (
        "\\begin{tabular}{@{}lcccccc@{}}\n\\toprule\n"
        "Cutoff & $n_{\\text{test}}$ & Prev. & C1 & C2 & C3 & M2 \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    t.add("tab_elliptic.tex",
          "Edge audit on Elliptic with real time steps (LightGBM read-out on 93 local features "
          "plus neighbour mean and max). The last cutoff is degenerate (test prevalence "
          f"{deg['test_prevalence']:.3f}) and is shown for completeness, not interpreted.",
          "tab:elliptic_protocol", body)
    return d


# ---------------------------------------------------------------- 滚动十折
def rolling(m: Macros, t: Tables) -> None:
    d = load("elliptic_rolling_matrix")
    sd = d["summary"]
    fd = d["folds_detail"]
    models = [("lightgbm", "LightGBM"), ("gcn", "GCN"), ("sage", "SAGE"), ("tgn_lite", "TGN-lite")]

    m.add("ROnFolds", str(len(fd)))
    m.add("ROLgbTemporal", f3(sd["lightgbm"]["temporal_mean"]))
    m.add("ROLgbRandom", f3(sd["lightgbm"]["random_mean"]))
    m.add("ROLgbDelta", s3(sd["lightgbm"]["delta_mean"]))
    m.add("ROLgbPos", str(sd["lightgbm"]["delta_positive_folds"]))
    m.add("ROTgnDelta", s3(sd["tgn_lite"]["delta_mean"]))
    m.add("ROTgnPos", str(sd["tgn_lite"]["delta_positive_folds"]))
    m.add("ROSageDelta", s3(sd["sage"]["delta_mean"]))
    m.add("ROSagePos", str(sd["sage"]["delta_positive_folds"]))
    m.add("ROGcnDelta", s3(sd["gcn"]["delta_mean"]))
    m.add("ROGcnPos", str(sd["gcn"]["delta_positive_folds"]))

    # 折级配对 CI（主模型）
    import statistics as st
    diffs = [r["models"]["lightgbm"]["random"] - r["models"]["lightgbm"]["temporal"] for r in fd]
    n = len(diffs)
    mu = sum(diffs) / n
    s = st.stdev(diffs)
    se = s / (n ** 0.5)
    tcrit = 2.262  # t_{0.975, 9}
    m.add("ROLgbCI", f"[{mu - tcrit * se:+.3f}, {mu + tcrit * se:+.3f}]")
    m.add("ROLgbSD", f3(s))

    healthy = [r for r in fd if r["test_prevalence"] >= 0.05]
    hd = [r["models"]["lightgbm"]["random"] - r["models"]["lightgbm"]["temporal"] for r in healthy]
    m.add("ROHealthyN", str(len(healthy)))
    m.add("ROHealthyPos", str(sum(1 for x in hd if x > 0)))
    m.add("ROHealthyDelta", s3(sum(hd) / len(hd)))
    for key, tag in (("gcn", "Gcn"), ("sage", "Sage"), ("tgn_lite", "Tgn"),
                     ("lightgbm", "Lgb")):
        hx = [r["models"][key]["random"] - r["models"][key]["temporal"] for r in healthy]
        m.add(f"RO{tag}PosHealthy", str(sum(1 for x in hx if x > 0)))

    lines = []
    for r in fd:
        cells = " & ".join(
            f"{r['models'][k]['temporal']:.3f} ({r['models'][k]['random']:.3f})" for k, _ in models
        )
        lines.append(f"{r['cutoff']} & {r['n_test']:,} & {r['test_prevalence']:.3f} & {cells} \\\\")
    body = (
        "\\begin{tabular}{@{}lcccccc@{}}\n\\toprule\n"
        "$c$ & $n_{\\text{test}}$ & Prev. & LightGBM & GCN & SAGE & TGN-lite \\\\\n\\midrule\n"
        + "\n".join(lines)
        + "\n\\midrule\n"
        + " & & mean & "
        + " & ".join(f"{sd[k]['temporal_mean']:.3f}" for k, _ in models) + " \\\\\n"
        + " & & excl.42 & "
        + " & ".join(
            f"{sum(r['models'][k]['temporal'] for r in fd if r['test_prevalence'] >= 0.05) / max(1, sum(1 for r in fd if r['test_prevalence'] >= 0.05)):.3f}"
            for k, _ in models) + " \\\\\n"
        + " & & $\\Delta$ & "
        + " & ".join(f"{sd[k]['delta_mean']:+.3f}" for k, _ in models) + " \\\\\n"
        + " & & $\\Delta>0$ & "
        + " & ".join(f"{sd[k]['delta_positive_folds']}/{sd[k]['n_folds']}" for k, _ in models) + " \\\\\n"
        + "\\bottomrule\n\\end{tabular}\n"
    )
    t.add("tab_rolling.tex",
          "Rolling-origin matrix on Elliptic: temporal PR-AUC with the random-split value in "
          "parentheses. Cutoff 42 has test prevalence 0.011 and collapses for every condition; "
          "it is retained to show the collapse is base-rate driven, not protocol driven.",
          "tab:rolling", body,
          note="Mean and $\\Delta$ (random minus temporal) include all ten folds. Cutoff 42 is degenerate ($\\rho=0.011$, AP near 0.01 for every model and condition); it is reported, not interpreted, and the sign counts excluding it are given in the text.")


# ---------------------------------------------------------------- Real-CATS 十折方差
def variance(m: Macros, t: Tables) -> None:
    d = load("variance_decomposition")
    folds = d["folds"]
    m.add("VARGrand", f3(d["grand_mean_AP"]))
    m.add("VARSd", f3(d["fold_SD"]))
    m.add("VARCI", f"[{d['grand_mean_CI95'][0]:.3f}, {d['grand_mean_CI95'][1]:.3f}]")
    m.add("VARFoldShare", pct(d["share"]["fold"]))
    m.add("VARBootShare", pct(d["share"]["bootstrap"]))
    m.add("VARSeedShare", f"{100 * d['share']['seed']:.2f}")
    if len(folds) >= 2:
        ratio = folds[0]["prev_test"] / folds[-1]["prev_test"]
        m.add("VARRatio", f"{ratio:.1f}")
        m.add("VARRatioWord", "twelfth" if 10 < ratio < 14 else f"{ratio:.0f}")

    lines = []
    for r in folds:
        span = r.get("span_days")
        span_s = f"{span:,.0f}" if span is not None else "---"
        lines.append(f"{r['fold']} & {r['n_test']:,} & {r['prev_test']:.3f} & "
                     f"{r['AP_mean']:.3f} & {span_s} \\\\")
    body = (
        "\\begin{tabular}{@{}lcccc@{}}\n\\toprule\n"
        "Fold & $n_{\\text{test}}$ & Prev. $\\rho$ & AP & Test span (d) \\\\\n\\midrule\n"
        + "\n".join(lines)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    t.add("tab_variance.tex",
          "Rolling-origin folds on Real-CATS ETH (ten cutoffs, three seeds each). "
          "AP tracks the test prevalence $\\rho$ almost monotonically.",
          "tab:variance", body)


# ---------------------------------------------------------------- 尺寸偏移
def sizeshift(m: Macros, t: Tables) -> None:
    d = load("size_shift_multisplit")
    rows = d["splits"]
    m.add("SSnSeeds", str(d["n_seeds"]))
    vals = [r["AP_mean"] for r in rows if r["split"] in ("60/40", "70/30", "75/25", "80/20")]
    m.add("SSlo", f3(min(vals)))
    m.add("SShi", f3(max(vals)))
    m.add("SSband", f3(max(vals) - min(vals)))
    rnd = next(r for r in rows if r["split"] == "random-matched-size")
    m.add("SSrandom", f3(rnd["AP_mean"]))
    m.add("SSinter", f3(next(r for r in rows if r["split"].startswith("interleaved"))["AP_mean"]))
    n75 = next(r for r in rows if r["split"] == "75/25")["AP_mean"]
    m.add("SSdropVsRandom", f"{100 * (rnd['AP_mean'] - n75) / rnd['AP_mean']:.0f}")
    base = 0.5352
    m.add("SSdropVsBase", f"{100 * (base - n75) / base:.1f}")
    m.add("SSabsDrop", f3(base - n75))
    m.add("SSbase", f3(base))

    lines = []
    for r in rows:
        name = {"interleaved-1-in-5": "interleaved", "random-matched-size": "random, matched"}.get(
            r["split"], r["split"])
        lines.append(
            f"{name} & {r['n_test']:,} & {r['size_ratio']:.1f} & {r['AP_mean']:.3f} & "
            f"[{r['CI95'][0]:.3f}, {r['CI95'][1]:.3f}] \\\\"
        )
    body = (
        "\\begin{tabular}{@{}lcccc@{}}\n\\toprule\n"
        "Split & $n_{\\text{test}}$ & Size ratio & PR-AUC & 95\\% CI \\\\\n\\midrule\n"
        + "\n".join(lines)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    t.add("tab_sizeshift.tex",
          "Size-shift sensitivity on Elliptic2 (LightGBM on pooled features, five seeds, "
          "test-set bootstrap 95\\% CI). The interleaved control takes every fifth subgraph "
          "by size rank as test.",
          "tab:sizeshift", body)


# ---------------------------------------------------------------- 漂移
def drift(m: Macros, t: Tables) -> None:
    d = load("drift_buckets")
    e2 = d["elliptic2"]["rows"]
    rc = d["real_cats"]["rows"]
    q1, q5 = e2[0], e2[-1]
    m.add("DRqone", f3(q1["AP"]))
    m.add("DRqfive", f3(q5["AP"]))
    m.add("DRpsiSmall", f2(q1["PSI_mean"]))
    m.add("DRpsiLarge", f2(q5["PSI_mean"]))
    act = [r for r in rc if r["bucket"].startswith("activity")]
    if act:
        m.add("DRactPsiHi", f2(act[0]["PSI_mean"]))
        m.add("DRactPsiLo", f2(act[-1]["PSI_mean"]))
        m.add("DRactAphi", f3(act[0]["AP"]))
        m.add("DRactAplo", f3(act[-1]["AP"]))
    m.add("DRmmdSmall", f"{q1['MMD']:.4f}")
    m.add("DRmmdLarge", f"{q5['MMD']:.4f}")
    m.add("DRksLarge", f"{q5['KS_mean']:.3f}")
    oldest = [r for r in rc if r["bucket"].startswith("age")][-1]
    m.add("DRoldAP", f3(oldest["AP"]))
    m.add("DRoldPrev", f3(oldest["prev"]))
    m.add("DRoldBucket", oldest["bucket"].replace("age ", ""))
    mid = [r for r in rc if r["bucket"].startswith("age")][2]
    m.add("DRmidAP", f3(mid["AP"]))
    m.add("DRmidPrev", f3(mid["prev"]))

    lines = []
    keep_e2 = {e2[0]["bucket"], e2[2]["bucket"], e2[-1]["bucket"]}
    for r in e2:
        if r["bucket"] not in keep_e2:
            continue
