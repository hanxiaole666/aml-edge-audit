def coarsening(m: Macros, t: Tables) -> None:
    d = load("step_coarsening")
    m.add("COARSEmin", f3(d["verdict"]["coarsening_delta_AP_range"][0]))
    m.add("COARSEmax", f3(d["verdict"]["coarsening_delta_AP_range"][1]))
    m.add("INJneg", s3(d["verdict"]["mean_delta_AP_negative_excess"]))
    m.add("INJpos", s3(d["verdict"]["mean_delta_AP_positive_excess"]))
    m.add("INJzero", s3(d["verdict"]["mean_delta_AP_lambda_zero"]))
    m.add("INJflip", "yes" if d["verdict"]["sign_flips_with_assortativity"] else "no")

    ks = sorted({r["K_target"] for r in d["injection"]})
    m.add("INJkSmall", f"{ks[0]:,}")
    m.add("INJkLarge", f"{ks[-1]:,}")
    # 同 K 下度数是否恒定
    dg = [r["delta_degree"] for r in d["injection"] if r["K_target"] == ks[0]]
    m.add("INJdegSpread", f"{max(dg) - min(dg):.4f}")
    neg1 = [r["delta_AP"] for r in d["injection"] if abs(r["lambda"] + 1) < 1e-9]
    pos1 = [r["delta_AP"] for r in d["injection"] if abs(r["lambda"] - 1) < 1e-9]
    m.add("INJlamNeg", s3(sum(neg1) / len(neg1)))
    m.add("INJlamPos", s3(sum(pos1) / len(pos1)))

    lines = []
    xdegs = []
    for r in d["coarsening"]:
        xdeg = r["n_cross_edges"] / r["n_test"]
        xdegs.append(xdeg)
        lines.append(
            f"{r['window']} & {r['n_test']:,} & {r['test_prevalence']:.3f} & {r['n_cross_edges']:,} & "
            f"{xdeg:.2f} & {r['cross_homophily']['excess']:+.3f} & {r['AP_keep']:.3f} & "
            f"{r['AP_remove']:.3f} & {r['delta_AP']:+.4f} \\\\"
        )
    m.add("COARSEXdegLo", f"{min(xdegs):.2f}")
    m.add("COARSEXdegHi", f"{max(xdegs):.2f}")
    inj = []
    for lam in (-1.0, -0.5, 0.0, 0.5, 1.0):
        cells = []
        for K in ks:
            r = next(x for x in d["injection"] if x["K_target"] == K and abs(x["lambda"] - lam) < 1e-6)
            cells.append(f"{r['delta_AP']:+.4f} & {r['degree_injected']:.4f}")
        inj.append(f"{lam:+.1f} & " + " & ".join(cells) + " \\\\")

    body = (
        "\\scriptsize\n\\setlength{\\tabcolsep}{1.6pt}\n"
        "\\begin{tabular}{@{}lcccccccc@{}}\n\\toprule\n"
        "Window & $n_{\\text{test}}$ & Prev. & Cross edges & Cross/Node & Excess & AP keep & AP remove & $\\Delta$AP " + chr(92)*2 + chr(10)
        + "\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n\n"
        "\\vspace{4pt}\n\\begin{tabular}{@{}lcccc@{}}\n\\toprule\n"
        f" & \\multicolumn{{2}}{{c}}{{K = {ks[0]:,}}} & \\multicolumn{{2}}{{c}}{{K = {ks[-1]:,}}} \\\\\n"
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n"
        "$\\lambda$ & $\\Delta$AP & Degree & $\\Delta$AP & Degree \\\\\n\\midrule\n"
        + "\n".join(inj)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    t.add("tab_coarsen.tex",
          "Top: time-step coarsening on Elliptic. Merging steps moves the split inside a window "
          "and creates cross-split edges whose excess stays near $+0.1$, which isolates the composition "
          "channel from the degree channel. Bottom: controlled injection of test--test edges at "
          "fixed count $K$, with the same-label rate set by $\\lambda$ (excess ranges from "
          f"{d['injection'][0]['excess']:+.3f} at $\\lambda=-1$ to "
          f"{d['injection'][-1]['excess']:+.3f} at $\\lambda=+1$).",
          "tab:coarsen", body)


